package Programs;

public class Datatypes {
public static void main(String[] args) {
	//primitive data types-8
	//byte
	byte a=10; //size : 1byte , range : -128 to 127
	
	//short
	short b=10; //size : 2byte
	
	//integer
	int c=4; //size : 4byte
	
	//long
	long d=5;//size : 8byte
	
	//boolean
	boolean f=true; //size : 1byte
	
	//float
	float n=33.4566f;//size : 4byte //f suffix used to tell the compiler that it is float value,
	                  // otherwise compiler consider it as double
	
	//double
	double l=66555.112333;//size : 8byte
	
	//char
	char p='c';//size : 2byte
	
	//nonprimitive --string,array,object
}
}

